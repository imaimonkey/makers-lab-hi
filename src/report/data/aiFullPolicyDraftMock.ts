export function policyArticleText(article: PolicyArticle): string {
  const items = (article.items ?? []).map((item) => typeof item === 'string' ? item : item.term + ': ' + item.definition)
  return [article.paragraphs.join(' '), ...items].filter(Boolean).join('\\n')
}

export function buildFullPolicyCopyText(policy: FullPolicyDraft): string {
  const common = policy.commonPolicy.sections.map((section) => [section.title, ...section.articles.map((article) => '제' + article.number + '조(' + article.title + ')\\n' + policyArticleText(article))].join('\\n\\n')).join('\\n\\n')
  const specials = policy.specialClauses.map((clause) => [clause.title, '추천 보장 문구\\n' + clause.recommendedCoverageCopy, ...clause.articles.map((article) => '제' + article.number + '조(' + article.title + ')\\n' + policyArticleText(article))].join('\\n\\n')).join('\\n\\n')
  const attachments = ['부속 명세', ...policy.attachments.map((item, index) => (index + 1) + '. ' + item.title + ': ' + item.description)].join('\\n')
  return [policy.documentTitle, common, specials, attachments].join('\\n\\n')
}
